/**
 * Generates src/generated.ts from the web components' custom-elements.json: for every component, a
 * `<Name>Spec` interface (its attributes as camelCase props), named unions for enumerated attributes
 * (`ButtonVariant`), the defaults (`ButtonDefaults`) and the events it fires (`ButtonEvents`).
 *
 * The React and React Native components extend these interfaces, so all three libraries share one API and
 * a change to a web component's attributes shows up as a type error where the other platforms disagree.
 */
import { readFileSync, writeFileSync } from 'fs';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const manifest = JSON.parse(readFileSync(require.resolve('@kalads/web-components/custom-elements.json'), 'utf8'));

const pascal = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

/** "primary|secondary" → "'primary' | 'secondary'"; "1|2|3" → "1 | 2 | 3". */
function tsType(text) {
  if (!text) return 'string';
  if (['boolean', 'string', 'number'].includes(text)) return text;
  if (!text.includes('|')) return 'string';
  return text
    .split('|')
    .map((v) => v.trim())
    .map((v) => (/^-?\d+(\.\d+)?$/.test(v) ? v : `'${v}'`))
    .join(' | ');
}

/** A field default from the manifest ("'primary'", "false", "3") as a TS literal, or undefined. */
function literal(text) {
  if (text === undefined) return undefined;
  if (/^(true|false|-?\d+(\.\d+)?)$/.test(text)) return text;
  if (/^'[^']*'$/.test(text)) return text;
  return undefined;
}

const declarations = manifest.modules
  .flatMap((m) => m.declarations ?? [])
  .filter((d) => d.tagName && d.tagName.startsWith('kds-'))
  .sort((a, b) => a.tagName.localeCompare(b.tagName));

const out = [
  '// Generated by scripts/generate.mjs from @kalads/web-components/custom-elements.json. Do not edit.',
  '',
];
const index = [];

for (const d of declarations) {
  const name = pascal(d.tagName.replace(/^kds-/, ''));
  const fields = new Map((d.members ?? []).filter((m) => m.kind === 'field').map((m) => [m.attribute ?? m.name, m]));
  const props = [];
  const defaults = [];
  for (const attr of d.attributes ?? []) {
    const key = attr.fieldName ?? camel(attr.name);
    let type = tsType(attr.type?.text);
    if (type.includes('|')) {
      const alias = `${name}${pascal(attr.name)}`;
      out.push(`export type ${alias} = ${type};`);
      type = alias;
    }
    const doc = attr.description ? `  /** ${attr.description.replace(/\*\//g, '*\\/')} */\n` : '';
    props.push(`${doc}  ${key}?: ${type};`);
    const value = literal(fields.get(attr.name)?.default ?? fields.get(key)?.default ?? attr.default);
    if (value !== undefined && value !== "''" && value !== 'false') defaults.push(`  ${key}: ${value},`);
  }
  const summary = d.summary ?? d.description?.split('\n')[0] ?? '';
  out.push(
    '',
    `/** \`<${d.tagName}>\`${summary ? `: ${summary}` : ''} */`,
    `export interface ${name}Spec {`,
    ...props,
    '}',
    '',
    `/** Default values of ${name}'s props (only those with a non-empty, non-false default). */`,
    `export const ${name}Defaults = {`,
    ...defaults,
    `} as const satisfies Partial<${name}Spec>;`,
    '',
    `/** Events \`<${d.tagName}>\` fires. React and React Native expose them as \`on<Name>\` callbacks. */`,
    `export type ${name}Events = ${(d.events ?? []).map((e) => `'${e.name}'`).join(' | ') || 'never'};`,
    '',
    `/** Named slots of \`<${d.tagName}>\`. React and React Native take them as props (\`children\` for the default slot). */`,
    `export type ${name}Slots = ${(d.slots ?? []).map((s) => `'${s.name || 'default'}'`).join(' | ') || 'never'};`,
  );
  index.push(`  { tag: '${d.tagName}', name: '${name}', events: [${(d.events ?? []).map((e) => `'${e.name}'`).join(', ')}] },`);
}

out.push(
  '',
  '/** Every component, with its web tag name and the events it fires. Used by the parity check. */',
  'export const COMPONENTS = [',
  ...index,
  '] as const;',
  '',
);

writeFileSync('src/generated.ts', out.join('\n'));
console.log(`[spec] generated ${declarations.length} component specs`);
