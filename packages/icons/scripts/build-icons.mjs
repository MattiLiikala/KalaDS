import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, basename } from 'path';
import { glob } from 'glob';
import { optimize } from 'svgo';

const isWatch = process.argv.includes('--watch');

const SVGS_DIR = 'src/svgs';
const COMPONENTS_DIR = 'src/components';
const INDEX_FILE = 'src/index.ts';
// Platform-neutral icon data, and the React / React Native components built from it (src/lib/).
const DATA_DIR = 'src/data';
const REACT_DIR = 'src/react';
const NATIVE_DIR = 'src/native';

const SVGO_CONFIG = {
  plugins: [
    'removeDoctype',
    'removeXMLProcInst',
    'removeComments',
    'removeMetadata',
    'removeTitle',
    'removeDesc',
    {
      name: 'removeAttrs',
      params: { attrs: ['width', 'height', 'fill', 'stroke'] },
    },
    'cleanupIds',
    'removeUselessDefs',
    'convertColors',
    'mergePaths',
  ],
};

function toPascalCase(str) {
  return str
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function generateComponent(name, optimizedSvg) {
  const className = `KdsIcon${toPascalCase(name)}`;
  const tagName = `kds-icon-${name}`;

  // The <svg> is always hidden from assistive technology; the host carries the role and name instead.
  const svg = optimizedSvg.replace('<svg', '<svg aria-hidden="true" focusable="false"');

  return `import { LitElement, html, css } from 'lit';
import { customElement, property } from 'lit/decorators.js';
import { unsafeSVG } from 'lit/directives/unsafe-svg.js';

/**
 * @element ${tagName}
 * @summary The "${name}" icon. Takes the text colour; size with --kds-icon-size.
 *
 * Decorative by default (hidden from assistive technology). Set the label attribute when the icon
 * carries meaning on its own: it is then announced as an image with that name.
 *
 * @attr {string} label - Accessible name. Leave empty for decorative icons.
 */
@customElement('${tagName}')
export class ${className} extends LitElement {
  static styles = css\`
    :host {
      display: inline-flex;
      align-items: center;
      justify-content: center;
      width: var(--kds-icon-size, 1.5rem);
      height: var(--kds-icon-size, 1.5rem);
      color: inherit;
      flex-shrink: 0;
    }
    svg {
      width: 100%;
      height: 100%;
      fill: currentColor;
    }
  \`;

  @property({ reflect: true }) label = '';

  private _internals = this.attachInternals();

  protected updated() {
    this._internals.role = this.label ? 'img' : null;
    this._internals.ariaLabel = this.label || null;
  }

  render() {
    return html\`\${unsafeSVG(\`${svg}\`)}\`;
  }
}

declare global {
  interface HTMLElementTagNameMap {
    '${tagName}': ${className};
  }
}
`;
}

/**
 * The optimised SVG as data: the viewBox and the shape elements with their attributes. The React and
 * React Native icon components render this data, so neither platform needs SVG markup in source.
 */
function toIconData(optimizedSvg) {
  const viewBox = /viewBox="([^"]+)"/.exec(optimizedSvg)?.[1] ?? '0 0 24 24';
  const inner = optimizedSvg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '');
  const nodes = [];
  for (const [, tag, attrs] of inner.matchAll(/<([a-z]+)([^>]*?)\/?>/g)) {
    if (tag === 'g') throw new Error(`[icons] groups aren't supported; flatten the SVG (${tag})`);
    const props = {};
    for (const [, key, value] of attrs.matchAll(/([a-z-]+)="([^"]*)"/g)) {
      props[key.replace(/-([a-z])/g, (_, c) => c.toUpperCase())] = value;
    }
    nodes.push([tag, props]);
  }
  return { viewBox, nodes };
}

const GENERATED = '// Generated by scripts/build-icons.mjs from src/svgs. Do not edit.\n';

function generatePlatformIcon(name, platform) {
  const component = `${toPascalCase(name)}Icon`;
  return `${GENERATED}import { createIcon } from '../lib/${platform}.js';
import data from '../data/${name}.js';

/** The "${name}" icon. Decorative unless it has a \`label\`. */
export const ${component} = createIcon('${component}', data);
`;
}

async function buildIcons() {
  const svgFiles = (await glob(`${SVGS_DIR}/*.svg`)).sort();

  if (svgFiles.length === 0) {
    console.log('[icons] no SVG files found in src/svgs/');
    return [];
  }

  for (const dir of [COMPONENTS_DIR, DATA_DIR, REACT_DIR, NATIVE_DIR]) {
    if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  }

  const names = [];

  for (const svgPath of svgFiles) {
    const name = basename(svgPath, '.svg');
    const raw = readFileSync(svgPath, 'utf-8');
    const optimized = optimize(raw, SVGO_CONFIG);
    const svg = optimized.data;

    const component = generateComponent(name, svg);
    writeFileSync(join(COMPONENTS_DIR, `kds-icon-${name}.ts`), component);
    writeFileSync(
      join(DATA_DIR, `${name}.ts`),
      `${GENERATED}import type { IconData } from '../lib/icon-data.js';\n\nexport default ${JSON.stringify(toIconData(svg))} satisfies IconData;\n`,
    );
    writeFileSync(join(REACT_DIR, `${name}.tsx`), generatePlatformIcon(name, 'react'));
    writeFileSync(join(NATIVE_DIR, `${name}.tsx`), generatePlatformIcon(name, 'native'));
    names.push(name);
  }

  const index = names
    .map((n) => `export { KdsIcon${toPascalCase(n)} } from './components/kds-icon-${n}.js';`)
    .join('\n') + '\n';

  writeFileSync(INDEX_FILE, index);

  for (const [dir, platform] of [[REACT_DIR, 'react'], [NATIVE_DIR, 'native']]) {
    const exports = names.map((n) => `export { ${toPascalCase(n)}Icon } from './${n}.js';`).join('\n');
    const names_ = names.map((n) => `  '${n}': ${toPascalCase(n)}Icon,`).join('\n');
    const imports = names.map((n) => `import { ${toPascalCase(n)}Icon } from './${n}.js';`).join('\n');
    writeFileSync(
      join(dir, 'index.ts'),
      `${GENERATED}${exports}\nexport { IconContext, type IconProps } from '../lib/${platform}.js';\nexport type { IconName } from '../lib/icon-data.js';\n\n${imports}\n\n/** Every icon by name, for components that take an icon name (\`<Icon name="search" />\`). */\nexport const icons = {\n${names_}\n} as const;\n`,
    );
  }
  writeFileSync(
    join(DATA_DIR, 'names.ts'),
    `${GENERATED}export const ICON_NAMES = ${JSON.stringify(names)} as const;\n`,
  );
  console.log(`[icons] generated ${names.length} icon components`);
  return names;
}

await buildIcons();

if (isWatch) {
  const { default: chokidar } = await import('chokidar');
  chokidar.watch(`${SVGS_DIR}/*.svg`).on('change', async (path) => {
    console.log(`[icons] changed: ${path}`);
    await buildIcons();
  });
  chokidar.watch(`${SVGS_DIR}/*.svg`).on('add', async (path) => {
    console.log(`[icons] added: ${path}`);
    await buildIcons();
  });
  console.log('[icons] watching src/svgs/*.svg');
}
